export function calibratedSpecificEdge(e: CanonEdge, r: Relationship): Relationship {
  const chosen =
    e.tuning ??
    (specific[e.from + ':' + e.to]
      ? { values: specific[e.from + ':' + e.to][0], attitude: specific[e.from + ':' + e.to][1] }
      : undefined);
  if (!chosen) return r;
  const [closeness, trust, familiarity] = chosen.values;
  return {
    ...r,
    closeness,
    trust,
    familiarity,
    attitude: chosen.attitude,
    stage: '原作关系事实 + 分方向模拟参数（非官方数值）',
    behavior: {
      competition: trust < 30 ? 0.8 : 0.3,
      banter: closeness >= 65 ? 0.65 : 0.2,
      initiativeScale: closeness >= 80 ? 1.4 : trust < 30 ? 0.6 : 1,
    },
  };
}
